export function getProvinceFromText(text) {
  if (!text) return null;
  const compact = text.trim().replace(/\s+/g, '');
  for (const [prefix, province] of PROVINCE_PREFIXES) {
    if (compact.startsWith(prefix)) return province;
  }
  return null;
}

// "서울 경기 강원 쪽하고 그 아래까지"(사용자 원문) — 강원 바로 아래 광역인
// 충청권(충북/충남/대전/세종)까지 포함한다. 전북/전남/광주/경북/경남/대구/부산/
// 울산/제주는 제외(남부). 실측(2026-09-21): 이 범위로 좁히면 전국 140,757건 중
// 약 86,667건, 고유 5km 격자 1,740개 → 하루 4회 기준 API 호출 약 6,960건으로
// 사용자가 가정한 일일 한도(10,000건)에 여유 있게 들어온다.
const NORTHERN_PROVINCES = new Set(['서울', '인천', '경기', '강원', '충북', '충남', '대전', '세종']);

// 주소를 우선 시도하고(더 완전한 형태로 들어오는 경우가 많음), 실패하면 sigungu_name으로
// 폴백한다(province.ts와 동일한 우선순위). 둘 다 판별 불가면(원본 데이터 이상) 이번엔
// "포함"이 아니라 "제외"한다 — province.ts는 사용자에게 보여줄 콘텐츠를 근거 없이
// 숨기지 않기 위해 판별 불가 시 포함시키지만, 이 배치는 반대로 "API 호출량을 확실히
// 줄이는 것"이 목적이라 판별 불가한 소수(실측 867건/140,757건)는 안전하게 제외한다
// (제3장 제5조 추측 금지 — 목적에 따라 안전한 기본값의 방향이 다르다는 것을 명시).
export function isNorthernRegionSpot(address, sigunguName) {
  const province = getProvinceFromText(address) ?? getProvinceFromText(sigunguName);
  if (!province) return false;
  return NORTHERN_PROVINCES.has(province);
}
