-- Task 9-6-7(2026-08-23): SEOUL_YEYAK 어댑터가 AREANM이 항상 서울 자치구라고 잘못 가정해
-- "서울시 " 접두를 무조건 붙인 결과, 서울시가 운영/위탁하지만 실제로는 서울 밖에 있는 시설
-- (서울대공원/서울동물원 등은 경기도 과천시, "상주서울농장"은 경상북도 상주시 등)에도
-- "서울시 과천시" 같은 존재하지 않는 행정구역명이 기록됐다. 실측(2026-08-23)으로 확인한
-- 서울 25개 자치구가 아닌 17개 값(과천시/상주시/제천시/함평군/남양주시/포천시/서천군/고양시,
-- 총 77건)에서만 "서울시 " 접두를 제거한다 — 실제 서울 자치구 값(예: "서울시 종로구")은
-- 손대지 않는다.
UPDATE events
SET sigungu_name = regexp_replace(sigungu_name, '^서울시\s+', '')
WHERE sigungu_name IN (
  '서울시 과천시', '서울시 상주시', '서울시 제천시', '서울시 함평군',
  '서울시 남양주시', '서울시 포천시', '서울시 서천군', '서울시 고양시'
);
